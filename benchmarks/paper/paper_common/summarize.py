"""Paper data summary: tidy figure-data CSVs + PAPER_DATA_SUMMARY.md, computed only from the E1/E2/E3/E5/E6 CSVs.

    python paper_common/summarize.py            # every card whose E1_<card>.csv exists (h100, a100, rtx5090, b200)

Cards are discovered from the CSV files, so a b200 CSV set is picked up automatically once it is present.
Writes paper_common/out/figures_data/*.csv, paper_common/out/<card>/{engine_not_fastest_cells,accuracy_red_rows,...}.csv and
benchmarks/paper/PAPER_DATA_SUMMARY.md.  Ratio convention everywhere: other / engine-cuda (> 1: the engine is faster).
"""

from __future__ import annotations

import csv
import math
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
OUT = HERE / "paper_common" / "out"
FIG = OUT / "figures_data"
CARDS_ALL = ["h100", "a100", "rtx5090", "b200"]
NAME = {"h100": "H100", "a100": "A100", "rtx5090": "RTX 5090", "b200": "B200"}
DT = {"master": "bf16", "float32": "fp32"}
BASE = ["pytorch", "triton", "cueq", "anthropic"]
MEM_BACKENDS = ["cuda", "pytorch", "triton", "cueq", "anthropic"]


def read(exp, eid, card):
    p = HERE / exp / f"{eid}_{card}.csv"
    if not p.exists():
        return []
    with open(p, newline="") as fh:
        return list(csv.DictReader(fh))


def write(path, rows, cols=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    cols = cols or (list(rows[0].keys()) if rows else ["empty"])
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def gm(xs):
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def f(x, n=2):
    return f"{x:.{n}f}"


def sci(x):
    try:
        return f"{float(x):.2e}"
    except ValueError:
        return x


def case_key(r):
    return (r["module"], r["mode"], r["row"], r["variant"], r["L"], r["depth"], r["samples"], r["dtype"])


def case_ms(rows):
    """case -> {backend: ms} over ok rows. pytorch / cuda / triton / cueq: engine stack; anthropic: kit stack."""
    out = defaultdict(dict)
    for r in rows:
        if r["status"] != "ok" or not r["ms_median"]:
            continue
        if (r["backend"] == "anthropic") != (r["stack"] == "kit"):
            continue
        out[case_key(r)][r["backend"]] = float(r["ms_median"])
    return out


def table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
    for r in rows:
        s += "| " + " | ".join(str(c) for c in r) + " |\n"
    return s + "\n"


def wgm(items):
    """items: list of dicts with geomean, n, min, max -> pooled (gm weighted by n, min, max, n)."""
    n = sum(a["n"] for a in items)
    if not n:
        return None
    return (math.exp(sum(math.log(a["geomean"]) * a["n"] for a in items) / n), min(a["min"] for a in items), max(a["max"] for a in items), n)


def main():
    cards = [c for c in CARDS_ALL if (HERE / "E1_operator_speed" / f"E1_{c}.csv").exists()]
    md = []
    P = md.append
    P("# Paper data summary (computed from the E1-E6 CSVs)\n")
    P("Generated by `benchmarks/paper/paper_common/summarize.py` (`paper_common/run_summary.sh`); no number below is typed by hand, every figure is computed from "
      "`benchmarks/paper/E*/E*_<card>.csv`. Cards found: " + ", ".join(NAME[c] for c in cards) + ". "
      "A B200 CSV set is picked up automatically when it is present (re-run the script).\n")
    P("## 0. Conventions\n")
    P("- Ratio = `other / engine cuda` of the same case (same requirements row, variant, L, depth, samples, dtype, mode); "
      "ratio > 1: the engine is faster. Only `status == ok` rows enter. Speedups are geometric means with `[min-max]` over the paired cases, last number = number of cases.\n"
      "- Backends: `pytorch` (eager reference, engine stack), `triton` (the engine's own portable Triton), `cueq` (cuEquivariance, where it serves the class), "
      "`anthropic` (Anthropic kernels, kit stack; the engine-stack cuda is paired with the kit-stack row of the same case).\n"
      "- dtype: `master` = fp32 master weights under bf16 autocast, shown as **bf16**; `float32` = **fp32** (measure/config.py: DTYPES master -> torch.bfloat16). "
      "mode `eval` = inference, `train` = forward + backward.\n"
      "- Timing: CUDA-graph replay median; E1/E2/E3/E6 H100 records 100 iterations, A100 / 5090 mixed 100 / 20, B200 E1 and E5 20, E5 20 (`benchmarks/paper/README.md`, iteration note). "
      "Nothing from paper/mac_20261119 is used.\n"
      "- Operator class = the E1 `module` column (every module of the requirements table).\n")

    # ---------------- E1 ----------------
    P("## 1. E1 operator speed\n")
    e1 = {c: read("E1_operator_speed", "E1", c) for c in cards}
    body = []
    for c in cards:
        st = Counter(r["status"] for r in e1[c])
        body.append([NAME[c], len(e1[c]), st["ok"], st["unsupported"], st["skipped"], st["failed"]])
    P(table(["card", "rows", "ok", "unsupported", "skipped", "failed"], body))

    agg, slower, noengine = [], [], []
    for c in cards:
        ms = case_ms(e1[c])
        cuda_status = {case_key(r): r["status"] for r in e1[c] if r["backend"] == "cuda"}
        grp = defaultdict(list)
        for k, b in ms.items():
            mod, mode, row, var, L, depth, samples, dt = k
            dt = DT.get(dt, dt)
            if "cuda" not in b:
                others = [x for x in BASE if x in b]
                if others:
                    noengine.append(dict(card=c, module=mod, mode=mode, dtype=dt, L=L, row=row, variant=var,
                                         engine_status=cuda_status.get(k, "missing"), baselines=";".join(others)))  # fmt: skip
                continue
            for v in BASE:
                if v in b:
                    ratio = b[v] / b["cuda"]
                    grp[(mod, mode, dt, v)].append(ratio)
                    if ratio < 1:
                        slower.append(dict(card=c, module=mod, mode=mode, dtype=dt, baseline=v, L=L, row=row, variant=var, depth=depth,
                                           samples=samples, engine_ms=b["cuda"], baseline_ms=b[v], ratio=ratio))  # fmt: skip
        for (mod, mode, dt, v), xs in grp.items():
            agg.append(dict(card=c, cls=mod, mode=mode, dtype=dt, vs=v, n=len(xs), geomean=gm(xs), min=min(xs), max=max(xs),
                            n_engine_faster=sum(x > 1 for x in xs)))  # fmt: skip
        write(OUT / c / "engine_not_fastest_cells.csv", [x for x in slower if x["card"] == c],
              ["card", "module", "mode", "dtype", "baseline", "L", "row", "variant", "depth", "samples", "engine_ms", "baseline_ms", "ratio"])  # fmt: skip
        write(OUT / c / "engine_missing_number_cells.csv", [x for x in noengine if x["card"] == c],
              ["card", "module", "mode", "dtype", "L", "row", "variant", "engine_status", "baselines"])  # fmt: skip
    write(FIG / "fig_speedup_by_class_card.csv", agg,
          ["card", "cls", "mode", "dtype", "vs", "n", "geomean", "min", "max", "n_engine_faster"])  # fmt: skip

    A = {(a["card"], a["cls"], a["mode"], a["dtype"], a["vs"]): a for a in agg}
    classes = sorted({a["cls"] for a in agg})

    P("### 1.1 Headline: geometric-mean speedup of engine cuda vs PyTorch eager, class x card (bf16 + fp32 pooled)\n")
    hdr = ["class"] + [f"{NAME[c]} {m}" for c in cards for m in ("eval", "train")]
    body = []
    for cls in classes:
        row = [cls]
        for c in cards:
            for m in ("eval", "train"):
                p = wgm([A[(c, cls, m, d, "pytorch")] for d in ("bf16", "fp32") if (c, cls, m, d, "pytorch") in A])
                row.append(f"{f(p[0])}x ({p[3]})" if p else "-")
        body.append(row)
    row = ["**all classes**"]
    for c in cards:
        for m in ("eval", "train"):
            p = wgm([a for a in agg if a["card"] == c and a["mode"] == m and a["vs"] == "pytorch"])
            row.append(f"**{f(p[0])}x** ({p[3]})" if p else "-")
    body.append(row)
    P(table(hdr, body))
    P("Filter: E1 rows with `status == ok`, backends `cuda` and `pytorch` (engine stack) of the same case; geometric mean of `pytorch_ms / cuda_ms` over all cases of the class and mode, "
      "both dtypes pooled (weighted by case count); `(n)` = number of cases. The last row pools every case (so classes with many cases weigh more). "
      "Min / max, the bf16 / fp32 split and the other baselines: section 1.2 and `paper_common/out/figures_data/fig_speedup_by_class_card.csv`.\n")

    P("### 1.2 Per card: engine cuda speedup by class, mode, dtype and baseline\n")
    P("Cell = `geomean [min-max] n`; `-` = no paired case with an ok row of that baseline.\n")
    for c in cards:
        for v in BASE:
            sub = [a for a in agg if a["card"] == c and a["vs"] == v]
            if not sub:
                P(f"**{NAME[c]} vs `{v}`**: no paired case.\n")
                continue
            P(f"**{NAME[c]}: engine cuda vs `{v}`**\n")
            body = []
            for cls in sorted({a["cls"] for a in sub}):
                row = [cls]
                for m in ("eval", "train"):
                    for d in ("bf16", "fp32"):
                        a = A.get((c, cls, m, d, v))
                        row.append(f"{f(a['geomean'])} [{f(a['min'])}-{f(a['max'])}] {a['n']}" if a else "-")
                body.append(row)
            tot = ["**all classes**"]
            for m in ("eval", "train"):
                for d in ("bf16", "fp32"):
                    p = wgm([a for a in sub if a["mode"] == m and a["dtype"] == d])
                    tot.append(f"{f(p[0])} [{f(p[1])}-{f(p[2])}] {p[3]}" if p else "-")
            body.append(tot)
            P(table(["class", "eval bf16", "eval fp32", "train bf16", "train fp32"], body))

    P("### 1.3 Cells where the engine cuda backend is NOT the fastest (a baseline is faster): to investigate\n")
    P("Filter: E1 paired cases (engine-stack `cuda` ok and baseline ok) with `baseline_ms < cuda_ms` (ratio < 1; ratio = baseline / engine, so < 1 means the baseline is faster). "
      "`clear` = ratio < 0.97 (outside +-3 % noise). Full per-case lists: `paper_common/out/<card>/engine_not_fastest_cells.csv` (with `engine_ms`; very short kernels, < 20 us, are noise-prone).\n")
    body = []
    for c in cards:
        for v in BASE:
            sl = [x for x in slower if x["card"] == c and x["baseline"] == v]
            n_pair = sum(a["n"] for a in agg if a["card"] == c and a["vs"] == v)
            body.append([NAME[c], v, n_pair, len(sl), sum(x["ratio"] < 0.97 for x in sl), f(min(x["ratio"] for x in sl), 3) if sl else "-"])
    P(table(["card", "baseline", "paired cases", "baseline faster (ratio < 1)", "of which clear (< 0.97)", "worst ratio"], body))
    for c in cards:
        sl = [x for x in slower if x["card"] == c and x["ratio"] < 0.97]
        g = defaultdict(list)
        for x in sl:
            g[(x["module"], x["mode"], x["dtype"], x["baseline"])].append(x)
        P(f"**{NAME[c]}: clear cases (ratio < 0.97) by class / mode / dtype / baseline** ({len(sl)} cases in {len(g)} groups; worst ratio first)\n")
        if not g:
            P("None.\n")
            continue
        body = []
        for k, xs in sorted(g.items(), key=lambda kv: min(x["ratio"] for x in kv[1])):
            w = min(xs, key=lambda x: x["ratio"])
            body.append([k[0], k[1], k[2], k[3], len(xs), f(w["ratio"], 3), f"L={w['L']} row={w['row']} {w['variant'][:60]}", f(w["engine_ms"] * 1e3, 1) + " us"])
        P(table(["class", "mode", "dtype", "baseline", "cases", "worst ratio", "worst case", "engine time"], body))
    if "b200" in cards:
        EXC = {"LayerNorm": "user-declared exception (known limit)", "SmoothLddtLoss": "user-declared exception"}
        sl = [x for x in slower if x["card"] == "b200"]
        P("#### 1.3a B200: every cell where a baseline (pytorch / triton / cueq / anthropic) is faster than the engine cuda\n")
        P("Rule: a baseline faster than the engine is a bug to investigate, except for the user-declared exceptions LayerNorm and SmoothLddtLoss (marked). "
          f"{len(sl)} paired cells in total (ratio = baseline / engine < 1); every cell is in `paper_common/out/b200/engine_not_fastest_cells.csv`.\n")
        g = defaultdict(list)
        for x in sl:
            g[(x["module"], x["baseline"])].append(x)
        body = []
        for (m, v), xs in sorted(g.items(), key=lambda kv: (kv[0][0] in EXC, kv[0])):
            body.append([m, v, len(xs), sum(x["ratio"] < 0.97 for x in xs), f(min(x["ratio"] for x in xs), 3), EXC.get(m, "NOT an exception: investigate")])
        P(table(["class", "baseline", "cells", "clear (< 0.97)", "worst ratio", "status"], body))
        rest = sorted([x for x in sl if x["module"] not in EXC], key=lambda x: x["ratio"])
        P(f"Cells outside the exceptions ({len(rest)}; all within the +-3 % noise band if the worst ratio is >= 0.97):\n")
        P(table(["class", "mode", "dtype", "baseline", "L", "row", "variant", "engine us", "baseline us", "ratio"],
                [[x["module"], x["mode"], x["dtype"], x["baseline"], x["L"], x["row"], x["variant"][:50], f(x["engine_ms"] * 1e3, 1), f(x["baseline_ms"] * 1e3, 1), f(x["ratio"], 3)] for x in rest]) if rest else "None.\n")  # fmt: skip
    P("Engine `cuda` without an ok number while a baseline has one (the engine's kernel table does not serve the case, skipped, or failed); lists in `paper_common/out/<card>/engine_missing_number_cells.csv`:\n")
    cnt = Counter((x["card"], x["module"], x["engine_status"]) for x in noengine)
    P(table(["card", "class", "engine cuda status", "cases"], [[NAME[a], m, s, n] for (a, m, s), n in sorted(cnt.items())]) if cnt else "None.\n")

    P("### 1.4 E1 rows that are not ok (inventory)\n")
    body = []
    for c in cards:
        cn = Counter((r["backend"], r["status"]) for r in e1[c] if r["status"] != "ok")
        body += [[NAME[c], b, s, n] for (b, s), n in sorted(cn.items())]
    P(table(["card", "backend", "status", "rows"], body))
    cn = Counter((NAME[c], r["module"], r["backend"], r["mode"], (r["reason"] or "")[:90]) for c in cards for r in e1[c] if r["status"] == "failed")
    if cn:
        P("`failed` rows (grouped):\n")
        P(table(["card", "class", "backend", "mode", "reason", "rows"], [list(k) + [n] for k, n in sorted(cn.items())]))

    # ---------------- E2 ----------------
    P("## 2. E2 sweeps (TriMul outgoing / TriAttn starting)\n")
    body, e2fig = [], []
    for c in cards:
        rows = read("E2_sweeps", "E2", c)
        if not rows:
            continue
        P(f"{NAME[c]}: {len(rows)} rows, status {dict(Counter(r['status'] for r in rows))}.\n")
        ms = defaultdict(dict)
        for r in rows:
            if r["status"] != "ok" or not r["ms_median"] or (r["backend"] == "anthropic") != (r["stack"] == "kit"):
                continue
            ms[(r["module"], r["mode"], r["L"], r["d"])][r["backend"]] = float(r["ms_median"])
            e2fig.append(dict(card=c, module=r["module"], mode=r["mode"], L=r["L"], d=r["d"], backend=r["backend"], ms=r["ms_median"]))
        g = defaultdict(list)
        for (mod, mode, L, d), b in ms.items():
            if "cuda" not in b:
                continue
            for sw, hit, ax in (("L sweep (d=128)", d == "128", int(L)), ("D sweep (L=768)", L == "768", int(d))):
                if hit:
                    for v in b:
                        if v != "cuda":
                            g[(mod, mode, sw, v)].append((b[v] / b["cuda"], ax))
        for (mod, mode, sw, v), xs in sorted(g.items()):
            r_ = [x[0] for x in xs]
            big = max(xs, key=lambda x: x[1])
            body.append([NAME[c], mod, mode, sw, v, len(xs), f(gm(r_)), f(min(r_)), f(max(r_)), f"{f(big[0])} at {'L' if sw[0] == 'L' else 'D'}={big[1]}"])
    write(FIG / "fig_e2_sweeps.csv", e2fig, ["card", "module", "mode", "L", "d", "backend", "ms"])
    P("Ratio = backend / engine cuda over the sweep grid points where both are ok (L sweep at d = 128, D sweep at L = 768); last column: ratio at the largest sweep point.\n")
    P(table(["card", "module", "mode", "sweep", "vs", "points", "geomean", "min", "max", "largest point"], body))

    # ---------------- E3 ----------------
    P("## 3. E3 accuracy lights (vs float64, judge tolerances)\n")
    fig3, body, reds, errs = [], [], [], []
    for c in cards:
        rows = read("E3_accuracy", "E3", c)
        P(f"{NAME[c]}: {len(rows)} rows, status {dict(Counter(r['status'] for r in rows))}.\n")
        cn = defaultdict(Counter)
        for r in rows:
            if r["status"] == "measured":
                cn[r["backend"]][r["light"]] += 1
                if r["light"] == "RED":
                    reds.append((c, r))
            elif r["status"] == "error":
                errs.append((c, r))
        for b, n in sorted(cn.items()):
            body.append([NAME[c], b, sum(n.values()), n["GREEN"], n["YELLOW"], n["RED"]])
            fig3 += [dict(card=c, backend=b, light=li, count=n[li], measured=sum(n.values())) for li in ("GREEN", "YELLOW", "RED")]
        write(OUT / c / "accuracy_red_rows.csv", [r for cc, r in reds if cc == c], list(rows[0].keys()) if rows else None)
        write(OUT / c / "accuracy_error_rows.csv", [r for cc, r in errs if cc == c], list(rows[0].keys()) if rows else None)
    write(FIG / "fig_accuracy_lights.csv", fig3, ["card", "backend", "light", "count", "measured"])
    P("Filter: `status == measured`; counts of the `light` column per backend (pytorch rows are included: pytorch vs float64 sets the tolerance).\n")
    P(table(["card", "backend", "measured", "GREEN", "YELLOW", "RED"], body))
    P("### 3.1 Every RED row\n")
    if not reds:
        P("None.\n")
    else:
        P(f"{len(reds)} RED rows (also `paper_common/out/<card>/accuracy_red_rows.csv`). err = error of the backend vs float64, err_pt = PyTorch's error, tol = tolerance.\n")
        body = [[NAME[c], r["module"], r["mode"], r["backend"], DT.get(r["dtype"], r["dtype"]), r["L"], f"row={r['row']} {r['variant'][:50]}", r["tensor"],
                 sci(r["err_backend"]), sci(r["err_pytorch"]), sci(r["tol"])] for c, r in reds]  # fmt: skip
        P(table(["card", "class", "mode", "backend", "dtype", "L", "case", "tensor", "err", "err_pt", "tol"], body))
    P("### 3.2 E3 rows with status `error`\n")
    cn = Counter((NAME[c], r["module"], r["backend"], r["mode"], (r["reason"] or "")[:80]) for c, r in errs)
    P(table(["card", "class", "backend", "mode", "reason", "rows"], [list(k) + [n] for k, n in sorted(cn.items())]) if cn else "None.\n")

    # ---------------- E6 ----------------
    P("## 4. E6 memory (peak GiB; TriMul outgoing / TriAttn starting; d = 128 L sweep)\n")
    mem, body = [], []
    for c in cards:
        rows = read("E6_memory", "E6", c)
        if not rows:
            continue
        P(f"{NAME[c]}: {len(rows)} rows, status {dict(Counter(r['status'] for r in rows))}.\n")
        by = defaultdict(dict)
        for r in rows:
            if r["d"] != "128" or (r["backend"] == "anthropic") != (r["stack"] == "kit") or r["status"] != "ok" or not r["peak_mem_gib"]:
                continue
            by[(r["module"], r["mode"], r["backend"])][int(r["L"])] = float(r["peak_mem_gib"])
            mem.append(dict(card=c, module=r["module"], mode=r["mode"], backend=r["backend"], L=r["L"], peak_mem_gib=r["peak_mem_gib"]))
        for mod, mode in sorted({(k[0], k[1]) for k in by}):
            eng, pt = by.get((mod, mode, "cuda"), {}), by.get((mod, mode, "pytorch"), {})
            common = sorted(set(eng) & set(pt))
            ratios = [pt[L] / eng[L] for L in common if eng[L] > 0]
            lm = [max(by[(mod, mode, b)]) if by.get((mod, mode, b)) else "-" for b in MEM_BACKENDS]
            top = common[-1] if common else None
            body.append([NAME[c], mod, mode, *lm,
                         f"{f(gm(ratios))}x [{f(min(ratios))}-{f(max(ratios))}] n={len(ratios)}" if ratios else "-",
                         f"L={top}: {f(pt[top])} vs {f(eng[top])} GiB ({f(pt[top] / eng[top])}x)" if top else "-"])  # fmt: skip
    write(FIG / "fig_memory_vs_L.csv", mem, ["card", "module", "mode", "backend", "L", "peak_mem_gib"])
    P("Largest L with an ok row per backend (grid L = 128 ... 2048; `skipped` rows are OOM on the card and are not re-routed). "
      "Ratio = PyTorch peak / engine cuda peak over the L points where both ran (geomean [min-max]); last column: the largest common L.\n")
    P(table(["card", "class", "mode"] + [f"max L {b}" for b in MEM_BACKENDS] + ["peak PyTorch / cuda", "largest common L"], body))

    # ---------------- E5 ----------------
    P("## 5. E5 other public kernels (AF3 setup: TriAttn d_pair 128 / 4 heads, L = 512 / 1024 / 2048, eval + train)\n")
    P("Full tables and the CUDA-graph validity check: [`E5_other_kernels/E5_results.md`](E5_other_kernels/E5_results.md); ds4sci graph timings are invalid, so for `invalid_graph` rows `ms_eager` is used and compared with the engine's `ms_eager` (cell suffix `e`). "
      "Best candidate = fastest candidate other than `pytorch` and engine `cuda` (cuEquivariance counts); ratio = candidate / engine (> 1: engine ahead). E5 is 20-iteration data.\n")
    e5fig = []
    for c in cards:
        rows = read("E5_other_kernels", "E5", c)
        if not rows:
            continue
        P(f"{NAME[c]}: {len(rows)} rows, status {dict(Counter(r['status'] for r in rows))}.\n")
        eng, cand = {}, defaultdict(list)
        for r in rows:
            k = (r["class"], DT.get(r["dtype"], r["dtype"]), r["mode"], r["L"])
            if r["backend"] == "cuda":
                eng[k] = r
            elif r["backend"] != "pytorch":
                cand[k].append(r)
        for k in sorted(set(eng) | set(cand), key=lambda k: (k[0], k[1], k[2], int(k[3]))):
            e = eng.get(k)
            e_ok = e is not None and e["status"] == "ok" and e["ms_median"] != ""
            best = None  # (score, backend, ms, engine_ms, basis)
            for r in cand.get(k, []):
                if r["status"] == "ok" and r["ms_median"]:
                    v, basis, ev = float(r["ms_median"]), "graph", (float(e["ms_median"]) if e_ok else None)
                elif r["status"] == "invalid_graph" and r["ms_eager"]:
                    v, basis = float(r["ms_eager"]), "eager"
                    ev = float(e["ms_eager"]) if e_ok and e["ms_eager"] else None
                else:
                    continue
                score = v / ev if ev else None
                if best is None or (best[0] is None and score is not None) or (score is not None and score < best[0]):
                    best = (score, r["backend"], v, ev, basis)
                elif score is None and best[0] is None and v < best[2]:
                    best = (score, r["backend"], v, ev, basis)
            if best:
                e5fig.append(dict(card=c, cls=k[0], dtype=k[1], mode=k[2], L=k[3], best_candidate=best[1], candidate_ms=best[2], engine_ms=best[3] or "",
                                  ratio=f"{best[0]:.4f}" if best[0] else "", basis=best[4], engine_status=e["status"] if e else "missing"))  # fmt: skip
        sub = [x for x in e5fig if x["card"] == c]
        P(f"**{NAME[c]}: best candidate per class (candidate / engine)**\n")
        body = []
        for cls, dt in sorted({(x["cls"], x["dtype"]) for x in sub}):
            for m in ("eval", "train"):
                row = [cls, dt, m]
                for L in ("512", "1024", "2048"):
                    x = next((x for x in sub if x["cls"] == cls and x["dtype"] == dt and x["mode"] == m and x["L"] == L), None)
                    if not x:
                        row.append("-")
                    elif x["ratio"]:
                        row.append(f"`{x['best_candidate']}` {f(float(x['ratio']))}" + ("e" if x["basis"] == "eager" else ""))
                    else:
                        row.append(f"no engine number ({x['engine_status']}); `{x['best_candidate']}` {float(x['candidate_ms']):.4g} ms")
                body.append(row)
        P(table(["class", "dtype", "mode", "L=512", "L=1024", "L=2048"], body))
        worst = [x for x in sub if x["ratio"] and float(x["ratio"]) < 1]
        P(f"Cells where the best candidate is faster than the engine: {len(worst)}"
          + ("." if not worst else ": " + "; ".join(f"{x['cls']} {x['dtype']} {x['mode']} L={x['L']} `{x['best_candidate']}` {float(x['ratio']):.3f}" for x in worst) + ".") + "\n")  # fmt: skip
    write(FIG / "fig_e5_ratios.csv", e5fig, ["card", "cls", "dtype", "mode", "L", "best_candidate", "candidate_ms", "engine_ms", "ratio", "basis", "engine_status"])

    P("## 6. Files\n")
