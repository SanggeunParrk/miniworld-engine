"""The token DiT attention core with all S samples in one program.

The samples of a sampling step share the hoisted pair bias exactly, but the packaged core (`tdit/attn.py`, grid
(S, m-tile, head)) has every sample read the whole bias: 5 x 18.9 MB of L2 traffic per block at L768, on top of the
141 MB of K/V re-reads, and the profile shows the kernel at ~57 % of both compute and memory SoL. Here one program owns
a (m-tile, head) for every sample: the bias tile is loaded once per key block and reused S times, which takes the bias
share down to 18.9 MB, and the S independent softmax/MMA chains give the scheduler something to overlap.

Everything else follows the packaged v5 core: logits already in the exp2 domain, the key mask folded into the bias,
head dim 48 split 32 + 16, the gate in the epilogue, output written over q.

Triton's parser has no list.append and no list comprehension, so the per-sample state cannot live in a python list:
the body is generated with S unrolled, written to `_gen/attn_sb<S>.py` (triton.jit reads a function's source from a
real file) and imported.
"""
import functools
import importlib.util
from pathlib import Path

import triton
import triton.language as tl

_SRC = '''# generated by attn_sb.py: the per-sample state unrolled S times
import triton
import triton.language as tl


@triton.jit
def _attn_fwd_gated_sb(Q, K, V, G, Bdesc, brow0, s0,
                       stride_qz, stride_qm, stride_qh, stride_qk,
                       H: tl.constexpr, N_CTX, HEAD_DIM: tl.constexpr, D1: tl.constexpr, D2: tl.constexpr,
                       EVEN: tl.constexpr, PREC: tl.constexpr,
                       BLOCK_M1: tl.constexpr, BLOCK_M2: tl.constexpr):
    start_m = tl.program_id(0)
    off_h = tl.program_id(1)
    offset_m = start_m * BLOCK_M1 + tl.arange(0, BLOCK_M1)
    offset_n = tl.arange(0, BLOCK_M2)
    k1 = tl.arange(0, D1)
    k2 = D1 + tl.arange(0, D2)
    mrow = offset_m[:, None] < N_CTX
    hbase = off_h.to(tl.int64) * stride_qh
    mofs = offset_m[:, None].to(tl.int64) * stride_qm
    nofs = offset_n[:, None].to(tl.int64) * stride_qm
{PROLOGUE}
    brow = brow0 + off_h * N_CTX + start_m * BLOCK_M1
    for start_n in range(0, N_CTX, BLOCK_M2):
        b = Bdesc.load([brow, start_n]).to(tl.float32)             # once for all the samples
        ro = start_n.to(tl.int64) * stride_qm
        nmask = (start_n + offset_n)[:, None] < N_CTX
{LOOP}
{EPILOGUE}
'''

_PRO = '''    base{i} = hbase + (s0 + {i}) * stride_qz      # hbase is int64, so this promotes
    qrow{i} = Q + base{i} + mofs
    if EVEN:
        q1_{i} = tl.load(qrow{i} + k1[None, :] * stride_qk)
        q2_{i} = tl.load(qrow{i} + k2[None, :] * stride_qk)
    else:
        q1_{i} = tl.load(qrow{i} + k1[None, :] * stride_qk, mask=mrow, other=0.0)
        q2_{i} = tl.load(qrow{i} + k2[None, :] * stride_qk, mask=mrow, other=0.0)
    m_{i} = tl.full([BLOCK_M1], -float("inf"), dtype=tl.float32)
    l_{i} = tl.zeros([BLOCK_M1], dtype=tl.float32)
    a1_{i} = tl.zeros([BLOCK_M1, D1], dtype=tl.float32)
    a2_{i} = tl.zeros([BLOCK_M1, D2], dtype=tl.float32)
'''

_LOOP = '''        kvrow{i} = base{i} + nofs + ro
        if EVEN:
            kk1 = tl.load(K + kvrow{i} + k1[None, :] * stride_qk)
            kk2 = tl.load(K + kvrow{i} + k2[None, :] * stride_qk)
        else:
            kk1 = tl.load(K + kvrow{i} + k1[None, :] * stride_qk, mask=nmask, other=0.0)
            kk2 = tl.load(K + kvrow{i} + k2[None, :] * stride_qk, mask=nmask, other=0.0)
        qk = tl.dot(q1_{i}, tl.trans(kk1), input_precision=PREC)
        qk = tl.dot(q2_{i}, tl.trans(kk2), qk, input_precision=PREC)
        sc = qk + b
        if not EVEN:
            sc = tl.where(((start_n + offset_n) < N_CTX)[None, :], sc, -float("inf"))
        m_new = tl.maximum(tl.maximum(m_{i}, tl.max(sc, 1)), -1e38)
        alpha = tl.math.exp2(m_{i} - m_new)
        p = tl.math.exp2(sc - m_new[:, None])
        l_{i} = l_{i} * alpha + tl.sum(p, 1)
        m_{i} = m_new
        if EVEN:
            v1 = tl.load(V + kvrow{i} + k1[None, :] * stride_qk)
            v2 = tl.load(V + kvrow{i} + k2[None, :] * stride_qk)
        else:
            v1 = tl.load(V + kvrow{i} + k1[None, :] * stride_qk, mask=nmask, other=0.0)
            v2 = tl.load(V + kvrow{i} + k2[None, :] * stride_qk, mask=nmask, other=0.0)
        pb = p.to(v1.dtype)
        a1_{i} = tl.dot(pb, v1, a1_{i} * alpha[:, None], input_precision=PREC)
        a2_{i} = tl.dot(pb, v2, a2_{i} * alpha[:, None], input_precision=PREC)
'''

_EPI = '''    inv{i} = 1.0 / tl.maximum(l_{i}, 1e-30)
    grow{i} = G + base{i} + mofs
    if EVEN:
        g1 = tl.load(grow{i} + k1[None, :] * stride_qk).to(tl.float32)
        g2 = tl.load(grow{i} + k2[None, :] * stride_qk).to(tl.float32)
        tl.store(qrow{i} + k1[None, :] * stride_qk, (a1_{i} * inv{i}[:, None] * tl.sigmoid(g1)).to(Q.dtype.element_ty))
        tl.store(qrow{i} + k2[None, :] * stride_qk, (a2_{i} * inv{i}[:, None] * tl.sigmoid(g2)).to(Q.dtype.element_ty))
    else:
        g1 = tl.load(grow{i} + k1[None, :] * stride_qk, mask=mrow, other=0.0).to(tl.float32)
        g2 = tl.load(grow{i} + k2[None, :] * stride_qk, mask=mrow, other=0.0).to(tl.float32)
        tl.store(qrow{i} + k1[None, :] * stride_qk, (a1_{i} * inv{i}[:, None] * tl.sigmoid(g1)).to(Q.dtype.element_ty), mask=mrow)
        tl.store(qrow{i} + k2[None, :] * stride_qk, (a2_{i} * inv{i}[:, None] * tl.sigmoid(g2)).to(Q.dtype.element_ty), mask=mrow)
'''


def _desc_pre_hook(nargs):
    nargs["Bdesc"].block_shape = [nargs["BLOCK_M1"], nargs["BLOCK_M2"]]


def _cfgs():
    return [triton.Config({"BLOCK_M1": m1, "BLOCK_M2": m2}, num_warps=w, num_stages=s, pre_hook=_desc_pre_hook)
            for m1 in (32, 64, 128) for m2 in (32, 64, 128) for w in (4, 8) for s in (1, 2, 3)]


@functools.lru_cache(maxsize=8)
def _kernel(sb: int):
    src = _SRC.format(PROLOGUE="".join(_PRO.format(i=i) for i in range(sb)),
                      LOOP="".join(_LOOP.format(i=i) for i in range(sb)),
                      EPILOGUE="".join(_EPI.format(i=i) for i in range(sb)))
    gen = Path(__file__).resolve().parent / "_gen"
    gen.mkdir(exist_ok=True)
    path = gen / f"attn_sb{sb}.py"
    if not path.exists() or path.read_text() != src:
        path.write_text(src)
    spec = importlib.util.spec_from_file_location(f"attn_sb{sb}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return triton.autotune(configs=_cfgs(), key=["N_CTX", "H", "HEAD_DIM", "PREC"], restore_value=["Q"])(
        mod._attn_fwd_gated_sb)


def attention_gated_sb(q, k, v, g, bdesc, block, precision="tf32", groups=None):
    """As tdit.attn.attention_gated_in_place2, but a program per (m-tile, head) covers a whole group of samples, so the
    bias tile is read once per group instead of once per sample. ``groups`` are the group sizes, e.g. (2, 3) for S = 5:
    one launch each, no wasted work, and the register pressure of a big group stays out of the kernel."""
    S, L, H, D = q.shape
    assert k.stride() == q.stride() and v.stride() == q.stride() and g.stride() == q.stride()
    d1 = 1 << (D.bit_length() - 1)
    d2 = D - d1
    grid = lambda c: (triton.cdiv(L, c["BLOCK_M1"]), H)             # noqa: E731
    s0 = 0
    for sb in groups or (S,):
        _kernel(sb)[grid](q, k, v, g, bdesc, block * H * L, s0, *q.stride(), H=H, N_CTX=L, HEAD_DIM=D, D1=d1, D2=d2,
                          EVEN=(L % 128 == 0), PREC=precision)
        s0 += sb
    assert s0 == S, f"groups {groups} do not cover {S} samples"
    return q
