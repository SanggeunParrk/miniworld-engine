# emits bf16 wgmma wrappers (f32 accumulate, K-major smem operands): SS and RS (A = 4 packed bf16x2 registers), n in {32, 64, 128},
# plus write-only "first of chain" variants (scale-d = 0) so ptxas knows the accumulator is dead before the chain starts.
def body(n, rs, first):
    nd = n // 2
    regs = "\n".join("      \" %s%s\\n\"" % (", ".join("%%%d" % r for r in range(k, min(k + 8, nd))), "," if k + 8 < nd else "") for k in range(0, nd, 8))
    outs = ", ".join(('"=f"(d[%d])' if first else '"+f"(d[%d])') % i for i in range(nd))
    base = nd if first else nd + 1
    if rs:
        aop = "{%%%d, %%%d, %%%d, %%%d}, %%%d" % (base, base + 1, base + 2, base + 3, base + 4)
        tail = "1, 1, 0"
        ins = '"r"(a0), "r"(a1), "r"(a2), "r"(a3), "l"(db)'
        sig = "uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint64_t db"
    else:
        aop = "%%%d, %%%d" % (base, base + 1)
        tail = "1, 1, 0, 0"
        ins = '"l"(da), "l"(db)'
        sig = "uint64_t da, uint64_t db"
    name = "mma_%s_n%d%s" % ("rs" if rs else "ss", n, "_first" if first else "")
    if first:
        return f'''__device__ __forceinline__ void {name}({sig}, float* d) {{
  asm volatile(
      "wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{\\n"
{regs}
      "}}, {aop}, 0, {tail};\\n"
      : {outs}
      : {ins} : "memory");
}}
'''
    return f'''__device__ __forceinline__ void {name}({sig}, float* d, int accumulate) {{
  asm volatile(
      "{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{nd}, 0;\\n"
      "wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{\\n"
{regs}
      "}}, {aop}, p, {tail};\\n}}\\n"
      : {outs}
      : "r"(accumulate), {ins} : "memory");
}}
'''
print("// ---- generated by gen/gen_wgmma_bf16.py ----")
for n in (32, 64, 128):
    for rs in (False, True):
        for first in (False, True):
            print(body(n, rs, first))
