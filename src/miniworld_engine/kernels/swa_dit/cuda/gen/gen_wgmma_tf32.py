# emits tf32 wgmma wrappers (f32 accumulate, K-major smem operands, no transpose -- tf32 has none): SS (A from a smem
# descriptor) and RS (A = 4 tf32 registers: rows g / g+8, k = t / t+4), n in {32, 64, 128}, plus write-only "first of
# chain" variants (scale-d = 0) so ptxas knows the accumulator is dead before the chain starts.
# Output: wgmma_tf32.inc, included by swa_fp32.cu.  Run: python gen_wgmma_tf32.py > wgmma_tf32.inc
def body(n, rs, first):
    nd = n // 2
    regs = "\n".join(
        '      " %s%s\\n"'
        % (
            ", ".join("%%%d" % r for r in range(k, min(k + 8, nd))),
            "," if k + 8 < nd else "",
        )
        for k in range(0, nd, 8)
    )
    outs = ", ".join(('"=f"(d[%d])' if first else '"+f"(d[%d])') % i for i in range(nd))
    base = nd  # no predicate operand: scale-d is an immediate
    if rs:
        aop = "{%%%d, %%%d, %%%d, %%%d}, %%%d" % (
            base,
            base + 1,
            base + 2,
            base + 3,
            base + 4,
        )
        ins = '"r"(a0), "r"(a1), "r"(a2), "r"(a3), "l"(db)'
        sig = "uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint64_t db"
    else:
        aop = "%%%d, %%%d" % (base, base + 1)
        ins = '"l"(da), "l"(db)'
        sig = "uint64_t da, uint64_t db"
    tail = "1, 1"
    name = "tf32_%s_n%d%s" % ("rs" if rs else "ss", n, "_first" if first else "")
    if first:
        return f"""__device__ __forceinline__ void {name}({sig}, float* d) {{
  asm volatile(
      "wgmma.mma_async.sync.aligned.m64n{n}k8.f32.tf32.tf32 {{\\n"
{regs}
      "}}, {aop}, 0, {tail};\\n"
      : {outs}
      : {ins} : "memory");
}}
"""
    return f"""__device__ __forceinline__ void {name}({sig}, float* d) {{
  asm volatile(
      "wgmma.mma_async.sync.aligned.m64n{n}k8.f32.tf32.tf32 {{\\n"
{regs}
      "}}, {aop}, 1, {tail};\\n"
      : {outs}
      : {ins} : "memory");
}}
"""


print("// ---- generated by gen/gen_wgmma_tf32.py ----")
for n in (32, 64, 128):
    for rs in (False, True):
        for first in (False, True):
            print(body(n, rs, first))
